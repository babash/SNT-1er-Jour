create table if not exists public.snt_responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default timezone('utc'::text, now()),
  student_name text not null,   -- « Prénom & Nom »
  student_class text not null,  -- la classe choisie dans la liste
  keywords text[],              -- les mots du nuage
  favorite_quotes integer[],    -- le numéro de la citation choisie (1 à 4)
  question text,                -- la question au prof
  fav_music text,               -- un lien YouTube
  fav_book text,                -- livre ou manga
  fav_movie text                -- série ou film
);

alter table public.snt_responses enable row level security;
