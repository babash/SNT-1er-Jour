-- Garde-fou : le bon rôle, le socle commun, et pas d'ancienne version dans public.
do $$
begin
  if current_user <> 'postgres' then
    raise exception 'À lancer en postgres (éditeur SQL de Supabase), pas en % : arrêt, rien n''a été modifié.', current_user;
  end if;
  if to_regprocedure('commun.essai_permis(text, text, integer)') is null or to_regprocedure('commun.noter_echec(text, text)') is null then
    raise exception 'Le socle commun manque : lancer d''abord supabase/schema.sql du dépôt du site Babash-NSI-SNT. Arrêt, rien n''a été modifié.';
  end if;
  if to_regclass('public.snt_responses') is not null then
    raise exception 'Ce projet a l''ancienne version (public.snt_responses) : appliquer 3-fonction-ajout.sql, puis 4-schema.sql (LISEZMOI.md). Arrêt, rien n''a été modifié.';
  end if;
  if to_regclass('snt_premier_jour.reponses') is not null
     and coalesce(obj_description(to_regclass('snt_premier_jour.reponses'), 'pg_class'), '') not like 'SNT 1er jour.%' then
    raise exception 'Une table snt_premier_jour.reponses existe déjà et ne vient pas de SNT 1er jour : arrêt, rien n''a été modifié.';
  end if;
end $$;

-- 1. Le schéma
create schema if not exists snt_premier_jour authorization postgres;
revoke all on schema snt_premier_jour from public, anon, authenticated;
comment on schema snt_premier_jour is
  'SNT 1er jour : le questionnaire du premier jour de SNT (seconde). Jamais exposé à l''API ; aucun droit pour anon ni pour authenticated. La page passe par public.snt_repondre et public.snt_nuage.';

-- 2. La fonction de la contrainte de taille des mots-clés
create or replace function snt_premier_jour.taille_max(t text[])
returns integer
language sql
immutable
set search_path = ''
as $$
  select coalesce(max(char_length(x)), 0) from unnest(t) as x;
$$;
revoke all on function snt_premier_jour.taille_max(text[]) from public, anon, authenticated, service_role;
comment on function snt_premier_jour.taille_max(text[]) is
  'SNT 1er jour, interne. La longueur du plus long élément d''un tableau de textes (0 s''il est vide) : la contrainte reponses_mots_cles_taille s''en sert. Ne lit aucune table.';

-- 3. La table des réponses
create table if not exists snt_premier_jour.reponses (
  id         bigint generated by default as identity,
  cree_le    timestamptz not null default timezone('utc'::text, now()),
  prenom_nom text not null,
  classe     text not null,
  mots_cles  text[],
  citations  integer[],
  question   text,
  musique    text,
  livre      text,
  film       text,
  constraint reponses_pkey primary key (id),
  constraint reponses_prenom_nom_taille check (char_length(prenom_nom) <= 80),
  constraint reponses_classe_taille check (char_length(classe) <= 20),
  constraint reponses_mots_cles_nombre check (cardinality(mots_cles) <= 10),
  constraint reponses_mots_cles_taille check (snt_premier_jour.taille_max(mots_cles) <= 40),
  constraint reponses_citations_nombre check (cardinality(citations) <= 4),
  constraint reponses_question_taille check (char_length(question) <= 500),
  constraint reponses_musique_taille check (char_length(musique) <= 300),
  constraint reponses_livre_taille check (char_length(livre) <= 100),
  constraint reponses_film_taille check (char_length(film) <= 100)
);
alter table snt_premier_jour.reponses enable row level security;
revoke all on table snt_premier_jour.reponses from public, anon, authenticated, service_role;

